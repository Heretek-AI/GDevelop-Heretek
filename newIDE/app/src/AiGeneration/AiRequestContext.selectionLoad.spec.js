const mockFn = (fn: any): JestMockFn<any, any> => fn;

const makeAiRequest = (id: string, status: 'working' | 'ready'): AiRequest => ({
  id,
  createdAt: '2024-01-01T00:00:00.000Z',
  updatedAt: '2024-01-01T00:00:00.000Z',
  userId: 'user-1',
  status,
  error: null,
  output: [],
  parentAiRequestId: null,
});

