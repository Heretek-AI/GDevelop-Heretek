const ContextCapture = ({
  contextRef,
}: {|
  contextRef: { current: AiRequestContextState | null },
|}) => {
  const context = React.useContext(AiRequestContext);
  contextRef.current = context;
  return null;
};

// Mounts useAiRequestState the same way AskAiEditorContainer does, so a
// second selection-load effect would race AiRequestProvider's loadAiRequest.
const AiRequestStateProbe = () => {
  useAiRequestState({ project: null });
  return null;
};

const flushPromises = async () => {
  for (let i = 0; i < 10; i++) {
    // eslint-disable-next-line no-await-in-loop
    await Promise.resolve();
  }
};

const getContext = (contextRef: {
  current: AiRequestContextState | null,
}): AiRequestContextState => {
  if (!contextRef.current) throw new Error('Context not captured');
  return contextRef.current;
};

const renderProviderWithAiRequestState = () => {
  const contextRef: { current: AiRequestContextState | null } = {
    current: null,
  };
  let renderer;
  act(() => {
    renderer = TestRenderer.create(
      <AuthenticatedUserContext.Provider value={makeAuthenticatedUser()}>
        <AiRequestProvider>
          <ContextCapture contextRef={contextRef} />
          <AiRequestStateProbe />
        </AiRequestProvider>
      </AuthenticatedUserContext.Provider>
    );
  });
  return { contextRef, renderer };
};

describe('selection load with useAiRequestState mounted', () => {
  let renderer = null;

  beforeEach(() => {
    jest.useFakeTimers();
    mockFn(getAiRequest).mockReset();
    mockFn(suspendAiRequest).mockReset();
    mockFn(getAiRequestStatuses).mockReset();
    mockFn(getAiRequestStatuses).mockResolvedValue([]);
    mockFn(fetchAiSettings).mockReset();
    mockFn(fetchAiSettings).mockResolvedValue(null);
    mockFn(getAiRequestSummaries).mockReset();
    mockFn(getAiRequestSummaries).mockResolvedValue({
      aiRequestSummaries: [],
      nextPageUri: null,
    });
  });

  afterEach(() => {
    act(() => {
      if (renderer) renderer.unmount();
    });
    renderer = null;
    jest.useRealTimers();
  });

  it('loads a chat exactly once when a profile is present', async () => {
    // Regression: useAiRequestState used to re-fetch the selected chat when a
    // profile was present, racing AiRequestProvider's loadAiRequest effect.
    const rendered = renderProviderWithAiRequestState();
    renderer = rendered.renderer;
    const contextRef = rendered.contextRef;

    const aiRequest = makeAiRequest('chat-1', 'ready');
    mockFn(getAiRequest).mockResolvedValue(aiRequest);

    act(() => {
      getContext(contextRef).setSelectedAiRequestId('chat-1');
    });
    await act(async () => {
      await flushPromises();
    });

    expect(mockFn(getAiRequest)).toHaveBeenCalledTimes(1);
    expect(getContext(contextRef).selectedAiRequest).toEqual(aiRequest);
    expect(
      getContext(contextRef).aiRequestStorage.aiRequestLoadingStates['chat-1']
    ).toBeUndefined();
  });

  it('keeps the selection when loading fails', async () => {
    // Regression: useAiRequestState used to clear selectedAiRequestId on a
    // failed secondary fetch, fighting the provider's retry UI.
    const rendered = renderProviderWithAiRequestState();
    renderer = rendered.renderer;
    const contextRef = rendered.contextRef;

    mockFn(getAiRequest).mockRejectedValue(new Error('Network error'));
    act(() => {
      getContext(contextRef).setSelectedAiRequestId('chat-1');
    });
    await act(async () => {
      await flushPromises();
    });

    expect(getContext(contextRef).selectedAiRequestId).toBe('chat-1');
    expect(mockFn(getAiRequest)).toHaveBeenCalledTimes(1);
    const loadingState = getContext(contextRef).aiRequestStorage
      .aiRequestLoadingStates['chat-1'];
    expect(loadingState.isLoading).toBe(false);
    expect(loadingState.error).toBeInstanceOf(Error);
  });
});
